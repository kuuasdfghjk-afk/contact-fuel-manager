-- 1. 共通設定テーブル (燃費・ガソリン単価)
CREATE TABLE IF NOT EXISTS public.settings (
    id INTEGER PRIMARY KEY DEFAULT 1,
    efficiency DOUBLE PRECISION NOT NULL DEFAULT 15,
    "fuelPrice" DOUBLE PRECISION NOT NULL DEFAULT 175,
    "updatedAt" TEXT NOT NULL DEFAULT ''
);

-- 2. コンタクトレンズ管理メンバーテーブル
CREATE TABLE IF NOT EXISTS public.members (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL DEFAULT '',
    "themeColor" TEXT NOT NULL DEFAULT 'blue',
    "startDate" TEXT NOT NULL,
    "deadlineDate" TEXT NOT NULL,
    memo TEXT NOT NULL DEFAULT '',
    "sortOrder" INTEGER NOT NULL DEFAULT 0,
    "updatedAt" TEXT NOT NULL DEFAULT ''
);

-- 3. 社用ガソリン 固定ルートプリセットテーブル
CREATE TABLE IF NOT EXISTS public.presets (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    km DOUBLE PRECISION NOT NULL DEFAULT 10,
    count INTEGER NOT NULL DEFAULT 0,
    "sortOrder" INTEGER NOT NULL DEFAULT 0
);

-- 4. 社用ガソリン 精算期限管理レコードテーブル
CREATE TABLE IF NOT EXISTS public.fuel_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "useDate" TEXT NOT NULL,
    deadline TEXT NOT NULL,
    mode TEXT NOT NULL,
    memo TEXT NOT NULL DEFAULT '',
    "bizKm" DOUBLE PRECISION NOT NULL DEFAULT 0,
    "bizLiters" DOUBLE PRECISION NOT NULL DEFAULT 0,
    "bizYen" INTEGER NOT NULL DEFAULT 0,
    "privLiters" DOUBLE PRECISION NOT NULL DEFAULT 0,
    "privYen" INTEGER NOT NULL DEFAULT 0,
    settled INTEGER NOT NULL DEFAULT 0,
    "createdAt" TEXT NOT NULL DEFAULT ''
);

-- 5. 自動通知・Cron・VAPID設定テーブル
CREATE TABLE IF NOT EXISTS public.notification_config (
    id INTEGER PRIMARY KEY DEFAULT 1,
    "cronTime" TEXT NOT NULL DEFAULT '08:00',
    "lastCronRunDate" TEXT NOT NULL DEFAULT '',
    "emailEnabled" INTEGER NOT NULL DEFAULT 1,
    "smtpHost" TEXT NOT NULL DEFAULT 'smtp.gmail.com',
    "smtpPort" INTEGER NOT NULL DEFAULT 587,
    "smtpUser" TEXT NOT NULL DEFAULT 'kuuasdfghjk@gmail.com',
    "smtpPass" TEXT NOT NULL DEFAULT '',
    "smtpFromName" TEXT NOT NULL DEFAULT 'コンタクト＆ガソリン期限管理Bot',
    "webPushEnabled" INTEGER NOT NULL DEFAULT 1,
    "vapidPublicKey" TEXT NOT NULL DEFAULT '',
    "vapidPrivateKeyPem" TEXT NOT NULL DEFAULT '',
    "lineEnabled" INTEGER NOT NULL DEFAULT 0,
    "lineChannelToken" TEXT NOT NULL DEFAULT '',
    "lineTargetUserId" TEXT NOT NULL DEFAULT ''
);

-- 6. Web Push 購読端末テーブル
CREATE TABLE IF NOT EXISTS public.push_subscriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    endpoint TEXT NOT NULL UNIQUE,
    p256dh TEXT NOT NULL DEFAULT '',
    auth TEXT NOT NULL DEFAULT '',
    "memberName" TEXT NOT NULL DEFAULT '全員',
    "userAgent" TEXT NOT NULL DEFAULT '',
    "createdAt" TEXT NOT NULL DEFAULT ''
);

-- 7. 通知実行履歴ログテーブル
CREATE TABLE IF NOT EXISTS public.notification_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "executedAt" TEXT NOT NULL,
    "triggerType" TEXT NOT NULL,
    channel TEXT NOT NULL,
    recipient TEXT NOT NULL,
    subject TEXT NOT NULL,
    body TEXT NOT NULL,
    status TEXT NOT NULL,
    detail TEXT NOT NULL DEFAULT ''
);

-- RLS (Row Level Security) をAnonキーから読み書き可能に設定（夫婦・家族間共有アプリ用）
ALTER TABLE public.settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.members ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.presets ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.fuel_records ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.notification_config ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.push_subscriptions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.notification_logs ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow all settings" ON public.settings;
CREATE POLICY "Allow all settings" ON public.settings FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow all members" ON public.members;
CREATE POLICY "Allow all members" ON public.members FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow all presets" ON public.presets;
CREATE POLICY "Allow all presets" ON public.presets FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow all fuel_records" ON public.fuel_records;
CREATE POLICY "Allow all fuel_records" ON public.fuel_records FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow all notification_config" ON public.notification_config;
CREATE POLICY "Allow all notification_config" ON public.notification_config FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow all push_subscriptions" ON public.push_subscriptions;
CREATE POLICY "Allow all push_subscriptions" ON public.push_subscriptions FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow all notification_logs" ON public.notification_logs;
CREATE POLICY "Allow all notification_logs" ON public.notification_logs FOR ALL USING (true) WITH CHECK (true);

