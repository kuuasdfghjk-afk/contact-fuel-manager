-- 2WEEKコンタクト＆社用ガソリンカード期限管理アプリ - Supabase 初期構築SQL
-- 使い方: Supabaseダッシュボード左メニュー「SQL Editor」→「New query」に貼り付けて「Run」を押すだけ！
